/**
 * Calcule les points pour une épreuve donnée
 * @param {string} epId   - id de l'épreuve
 * @param {string} genre  - 'H' ou 'F'
 * @param {number} valeur - secondes (chrono) ou nb passages (corde)
 * @returns {number} points (0 à 1000)
 */
function calcPoints(epId, genre, valeur) {
  const bareme = genre === 'H' ? BAREME_H : BAREME_F;
  const table = bareme[epId];
  if (!table) return 0;
  const ep = EPREUVES.find(e => e.id === epId);
  if (!ep) return 0;

  if (ep.type === 'passages') {
    // Logique inversée : on cherche le plus grand seuil ≤ valeur
    for (const [pts, seuil] of table) {
      if (valeur >= seuil) return pts;
    }
    return 0;
  } else {
    // Chrono : on cherche le premier seuil ≥ valeur
    for (const [pts, seuil] of table) {
      if (valeur <= seuil) return pts;
    }
    return 0;
  }
}

/**
 * Parse une saisie chrono "M:SS" ou "M'SS" ou secondes brutes → secondes
 */
function parseInput(str) {
  if (str === null || str === undefined || str === '') return null;
  const s = String(str).trim().replace(',', '.').replace("'", ':');
  if (s.includes(':')) {
    const [m, sec] = s.split(':');
    return parseInt(m) * 60 + parseFloat(sec);
  }
  return parseFloat(s);
}
